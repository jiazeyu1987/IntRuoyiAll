export const businessFieldOptions = Object.entries(labels)
  .filter(([key]) => !/hash|digest|sha256/i.test(key))
  .map(([value, label]) => ({ value, label }))

export const businessFieldLabel = (key: string) =>
  labels[key] || (/^[\u4e00-\u9fff][\u4e00-\u9fff0-9（）()、，：: /-]*$/.test(key) ? key : `未标注字段（${key}）`)

export const businessValueLabel = (field: string, value: unknown): string => {
  if (typeof value === 'boolean') return value ? '是' : '否'
  const text = String(value)
  if (field === 'dataScope') {
    const scopes: Record<string, string> = { '1': '全部数据', '2': '指定部门数据', '3': '本部门数据', '4': '本部门及下级部门数据', '5': '仅本人数据' }
    return scopes[text] || `未识别权限范围（${text}）`
  }
  if (field === 'field' && labels[text]) return labels[text]
  return enums[field]?.[text] || text
}

