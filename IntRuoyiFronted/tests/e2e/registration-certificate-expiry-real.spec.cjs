const { test, expect } = require('playwright/test')
test.setTimeout(360000)
const base = process.env.REG_CERT_E2E_BASE_URL
if (!base) throw new Error('REG_CERT_E2E_BASE_URL is required')

test('real FDA expiry and absent expiry remain consistent in list and detail', async ({ page }, testInfo) => {
  await page.goto(`${base}/login`, { waitUntil: 'domcontentloaded', timeout: 120000 })
  const form = page.locator('form.login-form:visible')
  await expect(form).toBeVisible({ timeout: 120000 })
  const tenant = form.locator('.el-select input').first()
  await tenant.fill('芋道源码')
  await page.getByRole('option', { name: '芋道源码', exact: true }).click()
  await form.locator('input.el-input__inner:not([type="password"]):visible').first().fill('admin')
  await form.locator('input[type="password"]').fill('admin123')
  await form.getByRole('button', { name: '登录', exact: true }).click()
  await expect(form).toBeHidden({ timeout: 60000 })
  await page.goto(`${base}/mdm/registration-certificate`, { waitUntil: 'domcontentloaded' })
  const view = page.getByTestId('registration-certificate-read-page')
  await expect(view).toBeVisible({ timeout: 90000 })
  await page.getByText('分类组合筛选与日期范围', { exact: true }).click()
  const type = view.locator('.el-form-item').filter({ has: page.locator('.el-form-item__label', { hasText: /^注册证类型$/ }) }).locator('.el-select')
  await type.click()
  await page.getByRole('option', { name: 'FDA', exact: true }).click()
  await page.getByRole('button', { name: '组合查询', exact: true }).click()
  await expect(view.locator('.el-loading-mask:visible')).toHaveCount(0, { timeout: 60000 })
  const expired = view.locator('tr.el-table__row').filter({ has: page.getByText('11.9测试', { exact: true }) })
  await expect(expired).toHaveCount(1)
  await expect(expired).toContainText('2026-11-01')
  await expect(expired.locator('.el-tag--danger').filter({ hasText: /^已过期$/ })).toHaveCount(2)
  await expect(expired).not.toContainText('当前版本')
  await expect(expired).not.toContainText('正常')
  const noExpiry = view.locator('tr.el-table__row').filter({ has: page.getByText('E2E-WORD1030-FDA注册证产品', { exact: true }) })
  await expect(noExpiry).toContainText('当前版本')
  await expect(noExpiry).toContainText('正常')
  await expect(noExpiry.locator('.el-tag--success').filter({ hasText: /^(当前版本|正常)$/ })).toHaveCount(2)
  await page.screenshot({ path: testInfo.outputPath('fda-list.png'), fullPage: true })
  await expired.getByRole('button', { name: '详情', exact: true }).click()
  const detail = page.getByTestId('registration-certificate-detail-page')
  await expect(detail.locator('.detail-title')).toContainText('11.9测试', { timeout: 60000 })
  await expect(detail.locator('.detail-title .el-tag--danger')).toHaveCount(2)
  await expect(detail.locator('.detail-title')).toContainText('已过期')
  await expect(detail.locator('.detail-title')).not.toContainText('当前版本')
  await page.screenshot({ path: testInfo.outputPath('fda-expired-detail.png'), fullPage: true })
  await page.reload({ waitUntil: 'domcontentloaded' })
  await expect(detail.locator('.detail-title .el-tag--danger')).toHaveCount(2, { timeout: 60000 })
  await page.goBack({ waitUntil: 'domcontentloaded' })
  await expect(noExpiry).toBeVisible({ timeout: 60000 })
  await noExpiry.getByRole('button', { name: '详情', exact: true }).click()
  await expect(detail.locator('.detail-title')).toContainText('E2E-WORD1030-FDA注册证产品', { timeout: 60000 })
  await expect(detail.locator('.detail-title')).toContainText('当前版本')
  await expect(detail.locator('.detail-title')).toContainText('正常')
  await expect(detail.locator('.detail-title .el-tag--danger')).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('fda-no-expiry-detail.png'), fullPage: true })
})
