// Run against the real task-owned three-page Word upload preview, never a mocked editor.
const { chromium } = require('playwright')
const { expect } = require('playwright/test')
const fs = require('node:fs')
const path = require('node:path')
;(async () => {
  const browser = await chromium.connectOverCDP(process.env.DCC_OFFICE_CDP || 'http://127.0.0.1:9339')
  try {
    const p = browser.contexts()[0].pages().find(p => p.url().includes('/dcc/controlled-file/upload'))
    if (!p) throw new Error('Open the task-owned office-navigation.docx in the real upload page first')
    const tools = p.getByTestId('office-navigation')
    const query = tools.getByRole('textbox', { name: '正文搜索关键词' })
    const pageNo = tools.getByRole('textbox', { name: '正文页码' })
    const button = name => tools.getByRole('button', { name, exact: true })
    const editor = p.frameLocator('.onlyoffice-viewer-frame__scaler > iframe')
    const out = path.resolve(__dirname, '../../../doc/tasks/20261113-document-preview')
    await expect(button('跳转')).toBeEnabled({ timeout: 60000 })
    await pageNo.fill('1')
    await button('跳转').click()
    await expect(tools).toContainText('第 1 / 3 页', { timeout: 60000 })
    await expect(button('上一页')).toBeDisabled()
    await query.fill('验收关键词')
    await button('搜索').click()
    await expect(tools).toContainText('第 1 / 3 处匹配')
    await button('下一处').click()
    await expect(pageNo).toHaveValue('2')
    await expect(tools).toContainText('第 2 / 3 处匹配')
    await expect(editor.locator('body')).toContainText('第2页共3页')
    if (!await p.locator('.protected-viewer-shell--expanded').count()) await p.getByRole('button', { name: '放大预览', exact: true }).click()
    await p.screenshot({ path: path.join(out, 'office-highlight.png'), fullPage: true })
    await button('下一处').click()
    await expect(pageNo).toHaveValue('3')
    await expect(editor.locator('body')).toContainText('第3页共3页')
    await expect(button('下一页')).toBeDisabled()
    await button('上一处').click()
    await expect(pageNo).toHaveValue('2')
    await button('上一页').click()
    await expect(pageNo).toHaveValue('1')
    await expect(editor.locator('body')).toContainText('第1页共3页')
    await button('下一页').click()
    await expect(pageNo).toHaveValue('2')
    await pageNo.fill('3')
    await button('跳转').click()
    await expect(pageNo).toHaveValue('3')
    await expect(editor.locator('body')).toContainText('第3页共3页')
    await tools.scrollIntoViewIfNeeded()
    await p.screenshot({ path: path.join(out, 'office-search.png'), fullPage: true })
    await query.fill('没有这个匹配词')
    await query.press('Enter')
    await expect(tools).toContainText('未找到匹配内容')
    await query.fill('验收关键词')
    await query.press('Enter')
    await expect(tools).toContainText('第 1 / 3 处匹配')
    await pageNo.fill('4')
    await button('跳转').click()
    await expect(tools.getByRole('alert')).toContainText('请输入 1 至 3 的页码')
    fs.writeFileSync(path.join(out, 'office-result.json'), JSON.stringify({ status: 'PASS', fixture: 'office-navigation.docx', cases: ['real Word preview', 'keyword search', 'enter search', 'previous/next match', 'cross-page highlight', 'previous/next page', 'specified page jump', 'first/last disabled', 'no match', 'out-of-range validation'] }, null, 2))
    console.log('PASS real Word search and page navigation')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
