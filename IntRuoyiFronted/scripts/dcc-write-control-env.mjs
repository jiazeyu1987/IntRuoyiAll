export function stripWriteControlEnv(env) {
  for (const name of writeControlEnvNames) {
    delete env[name]
  }
  return env
}

export function findPresentWriteControlEnvNames(env = process.env) {
  return writeControlEnvNames.filter((name) => env[name])
}

export function redactApprovalTokens(text) {
  return String(text || '').replace(/ALLOW_(TEST|PROD)_[A-Z0-9_]+/g, '<redacted-approval-token>')
}
