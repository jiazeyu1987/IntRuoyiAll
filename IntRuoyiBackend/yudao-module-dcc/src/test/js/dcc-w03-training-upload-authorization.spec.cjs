const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')
const source = fs.readFileSync(path.join(root, 'main/java/cn/iocoder/yudao/module/dcc/service/file/DccControlledFileUploadServiceImpl.java'), 'utf8')
test('training ticket creation delegates requester and task authorization to formal workflow before storage', () => {
  const begin = source.indexOf('boolean trainingRecord=')
  const end = source.indexOf('if (approvalPdf)', begin)
  assert.ok(begin >= 0 && end > begin)
  const branch = source.slice(begin, end)
  assert.doesNotMatch(branch, /trainingRecord\s*&&\s*!permissionApi\.hasAnyRoles/)
  assert.match(branch, /if\(trainingRecord\) workflowService\.validateTrainingRecordUpload\(userId,reqVO\.getControlledFileId\(\),reqVO\.getCategoryId\(\),ticketSessionId\)/)
  assert.ok(begin < source.indexOf('storePreviewFile(content, file)', end))
})
