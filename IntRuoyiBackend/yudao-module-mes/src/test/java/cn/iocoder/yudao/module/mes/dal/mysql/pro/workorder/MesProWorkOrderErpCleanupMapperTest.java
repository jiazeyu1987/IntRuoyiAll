    @Test void cleanupCommitPreventsLateProductionReference() throws Exception {
        var fixture = concurrentFixture();
        var cleanupLocked = new CountDownLatch(1);
        var allowCleanup = new CountDownLatch(1);
        var writerAttempt = new CountDownLatch(1);
        when(fixture.client.findExistingProductionOrderBillNos(any(), anyCollection())).thenAnswer(call -> {
            cleanupLocked.countDown();
            await(allowCleanup);
            return Set.of();
        });
        var writerMapper = spy(workOrderMapper);
        doAnswer(call -> {
            writerAttempt.countDown();
            return workOrderMapper.selectByIdForUpdate(call.getArgument(0));
        }).when(writerMapper).selectByIdForUpdate(fixture.workOrderId);
        var writer = new MesProWorkOrderServiceImpl();
        ReflectionTestUtils.setField(writer, "workOrderMapper", writerMapper);
        var executor = Executors.newFixedThreadPool(2);
        try {
            Future<Integer> cleanup = executor.submit(() -> inTenantTransaction(
                    () -> fixture.service.deleteMissing(fixture.request)));
            await(cleanupLocked);
            Future<Void> production = executor.submit(() -> inTenantTransaction(() -> {
                writer.validateWorkOrderConfirmedForUpdate(fixture.workOrderId);
                jdbc.update("INSERT INTO mes_pro_andon_record (id,work_order_id,tenant_id) VALUES (601,?,1)", fixture.workOrderId);
                return null;
            }));
            await(writerAttempt);
            allowCleanup.countDown();
            assertEquals(1, cleanup.get(10, TimeUnit.SECONDS));
            var failure = assertThrows(ExecutionException.class, () -> production.get(10, TimeUnit.SECONDS));
            assertInstanceOf(cn.iocoder.yudao.framework.common.exception.ServiceException.class, failure.getCause());
            assertNull(workOrderMapper.selectById(fixture.workOrderId));
            assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM mes_pro_andon_record WHERE work_order_id=?", Integer.class, fixture.workOrderId));
        } finally {
            allowCleanup.countDown();
            executor.shutdownNow();
            assertTrue(executor.awaitTermination(10, TimeUnit.SECONDS));
        }
    }

    @Test void committedProductionReferencePreventsWaitingCleanup() throws Exception {
        var fixture = concurrentFixture();
        var writerLocked = new CountDownLatch(1);
        var allowWriter = new CountDownLatch(1);
        var cleanupAttempt = new CountDownLatch(1);
        var cleanupWorkOrderMapper = spy(workOrderMapper);
        doAnswer(call -> {
            cleanupAttempt.countDown();
            return workOrderMapper.selectByIdForUpdate(call.getArgument(0));
        }).when(cleanupWorkOrderMapper).selectByIdForUpdate(fixture.workOrderId);
        ReflectionTestUtils.setField(fixture.service, "workOrderMapper", cleanupWorkOrderMapper);
        var writer = new MesProWorkOrderServiceImpl();
        ReflectionTestUtils.setField(writer, "workOrderMapper", workOrderMapper);
        var executor = Executors.newFixedThreadPool(2);
        try {
            Future<Void> production = executor.submit(() -> inTenantTransaction(() -> {
                writer.validateWorkOrderConfirmedForUpdate(fixture.workOrderId);
                jdbc.update("INSERT INTO mes_pro_andon_record (id,work_order_id,tenant_id) VALUES (602,?,1)", fixture.workOrderId);
                writerLocked.countDown();
                await(allowWriter);
                return null;
            }));
            await(writerLocked);
            Future<Integer> cleanup = executor.submit(() -> inTenantTransaction(
                    () -> fixture.service.deleteMissing(fixture.request)));
            await(cleanupAttempt);
            allowWriter.countDown();
            production.get(10, TimeUnit.SECONDS);
            var failure = assertThrows(ExecutionException.class, () -> cleanup.get(10, TimeUnit.SECONDS));
            assertInstanceOf(cn.iocoder.yudao.framework.common.exception.ServiceException.class, failure.getCause());
            assertTrue(failure.getCause().getMessage().contains("安灯"));
            assertNotNull(workOrderMapper.selectById(fixture.workOrderId));
            assertNotNull(syncRecordMapper.selectByWorkOrderId(fixture.workOrderId));
        } finally {
            allowWriter.countDown();
            executor.shutdownNow();
            assertTrue(executor.awaitTermination(10, TimeUnit.SECONDS));
        }
    }

