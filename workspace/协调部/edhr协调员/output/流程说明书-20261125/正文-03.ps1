Heading '一、明确返工对象和要求' $false
Step '准备：确认完整订单、批次、产品、原周期和问题事实，明确返工数量／范围、工序、重做及重新检验要求。系统要求正式返工方案或路线时必须满足，不随便选一条，也不直接改旧结果。'
Step '步骤 1｜PQC组长从待复核检验记录，或PQC负责人从正式生产放行申请，发起不合格审查，选择实际QA并核对唯一评审。发起详见《不合格评审操作说明》，不要两入口重复建单。'
Step '步骤 2｜QA核对事实、材料和返工要求，明确选择“返工”，填写具体意见，完成正常身份验证。提交一次后刷新，确认本次返工结论已保存。'
Picture 14 '图 1 QA返工材料与意见示例。内容为历史模拟测试，不能照搬为实际产品返工指令。'
Heading '二、核对旧周期结束和新周期来源'
Step '步骤 3｜生产组长从正常活跃订单／结果交接入口查看：旧周期按正式结果结束或返工关闭，新活跃周期能追溯原周期及本次评审。核对订单、批次与来源，不只凭产品名称相同判断关联。'
Picture 17 '图 2 新旧周期及评审关联示例。旧记录保留追溯，不用删除或重置制造“新周期”。'
Step '步骤 4｜从生产放行阶段发起的返工，PQC负责人还需核对原申请已返工／停止办理、原待办消除且保留追溯。不能只因列表空了，就声称已核实所有取消记录。'
Step '检查结果：新周期来源明确，旧周期和旧申请不能继续普通放行。关联不正确时暂停新周期填报，交责任岗处理。'
Heading '三、检查重新起算，生产组长正式接手'
Step '步骤 5｜进入新周期，确认生产和检验进度按实际返工规则重新起算。不能拿旧周期100%、合格结论、签名及资料直接当新周期完成。'
Picture 18 '图 3 新周期首工序数量归零示例。仅说明截图时点的该工序；其他工序和检验按本次正式要求核对。'
Step '步骤 6｜生产组长通过本轮正式接手入口，按返工范围安排人员、工序和数量，完成一笔合法的新周期生产提交及所需复核。新周期存在或入口可打开，不等于接手成功。'
Step '注意：设备、必填、人员资格及身份验证仍需满足。旧通知失效时从正常入口查当前任务，不反复点旧链接或重做旧评审。'
Heading '四、查回新记录，再完成返工与检验'
Step '步骤 7｜刷新新周期报工历史，确认新记录的周期、人员、工序、数量及复核结果正确，再核对本次返工结果交接状态。查不到先查清，不重复报工或签名。'
Picture 19 '图 4 新周期生产记录与正式复核示例。这是一笔接手后的记录，不代表整批返工已全部完成。'
Step '步骤 8｜继续完成返工要求的其余工序、重新检验及独立复核。需要新一轮完工和放行时，再核对生产／检验双100%，依次办理完工申请、PQC生产放行、四类资料及上市放行。'
Step '分清终点：返工交接办结＝结论查回、新旧关联正确、进度重新起算、生产组长已有新周期正式生产记录且交接完成。整批返工及放行完成＝要求的重做、再检验、复核及后续放行全部办完。前者不能冒充后者。'
