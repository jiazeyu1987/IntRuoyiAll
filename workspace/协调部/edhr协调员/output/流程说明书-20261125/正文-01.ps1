Start-Manual '导入活跃订单至上市放行操作说明 V1' '目的：指定订单加入活跃池后，完成生产、检验、独立复核、生产放行和资料上传，最终查到“已上市放行”。本流程不执行归档。'
Heading '一、确认前提，把订单加入活跃池' $false
Step '准备：确认完整订单号、批号、产品和数量；产品已关联正确且启用的工艺路线，版本已发布，检验规则和人员已配置。“版本已生效”不等于路线开关已开启。各岗使用自己的授权账号，密码、PIN不写入文件。'
Step '步骤 1｜生产组长进入“eDHR批记录 → 生产执行 → 生产班长 → 活跃订单池”，先查本单是否已在池中。未加入才点击“新增活跃订单”，在“订单号/产品”搜索完整订单号，核对产品并选择正式候选。'
Step '步骤 2｜本地没有订单时，在“ERP订单号”输入完整编号，点击“从 ERP 同步”；这一步只同步本地订单列表，还需从上方候选选择并确认加入。候选不可选时处理显示的原因，不用“数据”“数据2”或重置代替导入。'
Picture 2 '图 1 活跃订单池及“新增活跃订单”入口示例。ERP同步与加入活跃池是两步；弹窗字段按当前页面核对。'
Step '检查结果：刷新后能找到本单，订单、批次、产品、数量及路线正确。找不到或显示失败，不能当作导入完成。'
Heading '二、填写生产记录，完成生产复核'
Step '步骤 3｜生产组长按本单工序顺序进入报工页，选择适用的生产人员，填写数量、损耗、设备和工艺参数。可多人、分批提交；不要把整单数量重复填入每一笔。'
Step '步骤 4｜核对后正式提交，按系统要求办理生产复核和分配，再从报工历史查回人员、工序、数量及结果。退回记录按意见修改，成功记录不重复提交。'
Picture 3 '图 2 生产工序填写页示例。红色数值是历史模拟异常，不是推荐值；实际填写依本批生产要求。'
Step '注意：生产损耗不等于不合格；数量、参数超限颜色提示也不自动等于不合格。保留原值，按规则处理，不为变绿而填假数据。'
Heading '三、完成检验与逐条独立复核'
Step '步骤 5｜PQC检验员进入“检验填报”，选择本单、工序和首检／巡检轮次，按本单冻结的检验规则填写应检项目、样本、判定与损耗，完成身份验证并提交。界面列出项目，不代表每个阶段都要检。'
Picture 4 '图 3 检验填报示例。图中9/9、12/12是该示例提交数，不是所有订单的固定轮次，更不能代替复核结果。' 14.5
Step '步骤 6｜PQC组长进入“PQC管理”，逐条核对正式检验记录、样本及差异。符合要求才通过；不符则说明原因，按正式流程处理。提交后刷新待复核和历史，确认本单要求的记录均已复核。'
Picture 5 '图 4 检验复核历史示例。核对本单、本轮与结果；不要把历史21条套成其他订单的固定数量。' 14.5
Heading '四、双100%后申请并办理生产放行'
Step '步骤 7｜生产组长回到活跃订单，确认生产100%、经复核的检验100%，点击“完工 → 申请放行”。核对确认框中的订单后提交一次，刷新查到待PQC放行状态和正式申请。'
Picture 6 '图 5 完工与申请放行确认框示例。双100%不等于已放行，申请成功并查回才交下岗。' 14.5
Step '步骤 8｜PQC负责人进入“生产放行”，用完整工单号定位本次申请，核对生产、检验、差异和必要前置，符合条件才完成正常身份验证并放行。有实际不合格需评审时，转《不合格评审操作说明》。'
Picture 7 '图 6 PQC生产放行后的详情及产品信息示例。查回生产放行结果，再上传资料，不等于已经上市放行。' 14.5
Heading '五、放行后，由责任人上传四类资料'
Step '步骤 9｜本单PQC生产放行成功后，各资料责任人从本人正式任务进入，分别上传①来料检验报告、②灭菌报告、③成品检验报告、④成品检验记录。可提前准备，不提前上传到未放行订单。'
Step '步骤 10｜核对订单、批次、文件类别与内容，选择格式有效的文件并保存。刷新后再打开本单资料区，确认附件可见、归属正确且能查看；只选择了文件不等于保存成功。'
Picture 8 '图 7 成品检验报告与记录的正式附件示例。来料、灭菌资料分别由对应责任人办理，不用一份文件冒充四类资料。'
Step '检查结果：四类资料齐全且与本批一致，本人任务按实际结果办结。测试材料标“模拟”，不得伪造真实报告或签章。'
Heading '六、上市放行，并重新查询结果'
Step '步骤 11｜管理者代表从本人上市放行任务进入，核对本单PQC放行、四类资料和待处理问题。满足要求后填写结论，完成身份验证并提交，不代前面岗位补批准。'
Step '步骤 12｜刷新并重新进入本单详情／历史，确认“已上市放行”、办理人、时间及可见回执。未知先查询，不重复签名、提交；最后只记录归档待办，不执行归档。'
Picture 10 '图 8 历史测试单重新进入详情后的上市放行结果。图中订单与前面部分截图不同，不代表某个当前订单已完成。'
Step '完成标准：生产与检验复核完成 → 完工申请成功 → PQC生产放行成功 → 四类资料保存齐全 → 实际上市放行并查回。停在任一步都不能报告整链完成。'
Step '遇到阻塞：提示路线未绑定／未启用，核对产品关联、路线开关及版本；提交报错先查是否已保存。不得跳过必填、设备要求、独立复核或身份验证。'
